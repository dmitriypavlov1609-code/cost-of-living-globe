export type Lang = 'en' | 'ru';
export type Currency = 'USD' | 'RUB';

export const RUB_PER_USD = 95;

export function formatMoney(usd: number, currency: Currency, lang: Lang): string {
  if (currency === 'RUB') {
    const rub = Math.round(usd * RUB_PER_USD);
    return new Intl.NumberFormat('ru-RU', {
      style: 'currency',
      currency: 'RUB',
      maximumFractionDigits: 0,
    }).format(rub);
  }
  return new Intl.NumberFormat(lang === 'ru' ? 'ru-RU' : 'en-US', {
    style: 'currency',
    currency: 'USD',
    maximumFractionDigits: 0,
  }).format(usd);
}

